import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { utilitiesOf } from "../../../packages/themes-shared/src/utilities.js";
import {
  buildSpec,
  readPalette,
  render,
  THEMES,
  themeFailures,
  type Accent,
  type ThemeSpec,
} from "../src/build.js";

const palette = readPalette();
const fixture = join(import.meta.dirname, "fixtures/mauve.json");
const read = (id: string): string => readFileSync(join(THEMES, `${id}.css`), "utf8");

/** The suite's own light accent, as a spec would write it. */
const PEACH: Accent = {
  name: "peach",
  fill: "#fab387",
  fillHover: "#ef9f6e",
  label: "#080d1c",
  text: "#a03604",
  textHover: "#8a2e03",
  edge: "#a03604",
};
const theme = (accent: Partial<Accent> = {}, extra: Partial<ThemeSpec> = {}): ThemeSpec => ({
  id: "brand-check",
  base: "slash-suite",
  name: "Brand check",
  about: "a theme the tests build and never write.",
  accent: { ...PEACH, ...accent },
  ...extra,
});

/** Each utility's declarations, comments and the scope aside, so two themes compare by value. */
const values = (css: string): Record<string, Record<string, string>> =>
  Object.fromEntries(utilitiesOf(css));

describe("render", () => {
  it("rebuilds the base exactly when the accent is the base's own", () => {
    // Rebuilt with the suite's own peach, every utility paints what the base paints: the builder
    // touches the accent's slots and nothing else.
    const css = render(theme(), "test");
    expect(values(css)).toEqual(values(read("slash-suite")));
    expect(themeFailures(css, palette)).toEqual([]);
  });

  it("sets every accent slot from the spec", () => {
    const css = buildSpec(fixture)[0]?.css ?? "";
    expect(values(css)).toMatchObject({
      "bg-violet-600": { "background-color": "#cba6f7" },
      "hover:bg-violet-700": { "background-color": "#ba96e5" },
      "text-violet-600": { color: "#7c26e0" },
      "hover:text-violet-700": { color: "#6f02cf" },
      "focus-visible:outline-violet-600": { "outline-color": "#7c26e0" },
      // A tint keeps the base's alpha in the new colour.
      "bg-violet-50": { "background-color": "rgba(203, 166, 247, 0.2)" },
    });
    expect(css).toMatch(/--hc-accent: #7c26e0;/);
    expect(css).toMatch(/\.mauve-check ::selection,\n\.mauve-check::selection \{/);
  });

  it("leaves every other utility as the base has it", () => {
    const built = values(buildSpec(fixture)[0]?.css ?? "");
    const base = values(read("slash-suite"));
    // The label is the base's own ink, so `text-violet-50` is not among the changed.
    const changed = Object.keys(base).filter(
      (utility) => JSON.stringify(base[utility]) !== JSON.stringify(built[utility]),
    );
    expect(changed.toSorted()).toEqual(
      [
        "accent-violet-600",
        "bg-indigo-400/25",
        "bg-violet-50",
        "bg-violet-600",
        "border-violet-600",
        "focus-visible:outline-violet-600",
        "has-focus-visible:outline-violet-600",
        "hover:bg-violet-50",
        "hover:bg-violet-700",
        "hover:border-violet-400",
        "hover:text-violet-700",
        "link",
        "outline-violet-600",
        "target:outline-violet-600",
        "text-purple-700",
        "text-violet-600",
        "text-violet-700",
      ].toSorted(),
    );
  });

  it("renames the scope, the dark variant included, and leaves no trace of the base's", () => {
    const dark = buildSpec(fixture)[1]?.css ?? "";
    expect(dark).toContain(
      "@custom-variant dark (&:where(.mauve-check-dark, .mauve-check-dark *));",
    );
    expect(dark).not.toMatch(/\.slash-suite-dark(?![\w-])/);
    expect(dark).toMatch(/^\/\*! Catppuccin Mocha/);
    expect(dark).toContain("Generated by tools/theme-builder from themes/slash-suite-dark.css");
  });

  it("keeps every line within the formatter's width, so a rebuild is byte for byte", () => {
    for (const built of buildSpec(fixture)) {
      const long = built.css.split("\n").filter((line, i) => line.length > 100 && i > 0);
      const base = read(built.id.endsWith("-dark") ? "slash-suite-dark" : "slash-suite");
      expect(long.filter((line) => !base.includes(line.slice(-40)))).toEqual([]);
    }
  });

  it("refuses a colour that is not opaque, naming the field", () => {
    expect(() => render(theme({ text: "rgba(0, 0, 0, 0.5)" }), "test")).toThrow(
      'brand-check: accent.text: "rgba(0, 0, 0, 0.5)" is not an opaque colour',
    );
  });

  it("refuses an id that is the base's own", () => {
    expect(() => render(theme({}, { id: "slash-suite" }), "test")).toThrow(
      "slash-suite: the id must differ from the base",
    );
  });
});

describe("themeFailures", () => {
  it("names each contract a built theme fails", () => {
    // Latte's mauve is 4.45:1 on the suite's subtle strip, under AA.
    const failures = themeFailures(render(theme({ text: "#8839ef" }), "test"), palette);
    expect(failures).toContain(
      "accent text: text-violet-600 #8839ef on bg-slate-50 #e6e9f1 is 4.45:1, needs 4.5:1",
    );
  });

  it("passes the fixture, light and dark", () => {
    expect(buildSpec(fixture).map((built) => built.failures)).toEqual([[], []]);
  });
});
